#!/usr/bin/env node
/**
 * Phase 33B — establish a valid SQLite migration history WITHOUT touching the
 * PostgreSQL history and WITHOUT touching prisma/dev.db.
 *
 * Why a restructure is required
 * -----------------------------
 * Prisma 5.x supports exactly one migration directory per schema, always
 * `<schemaDir>/migrations`, and every `migrate` command reads
 * `migrations/migration_lock.toml`. That lock currently says `postgresql`
 * while the datasource says `sqlite`, so every migrate command fails with
 * P3019 before doing anything. The directory also contains a PostgreSQL-only
 * baseline (BYTEA, ADD CONSTRAINT) that cannot execute on SQLite.
 *
 * Design chosen (see PHASE_33_MIGRATION_PROVIDER_DECISION.md):
 *   prisma/migrations.postgresql/  <- PostgreSQL history, preserved verbatim,
 *                                     NOT applied to the SQLite database
 *   prisma/migrations/             <- SQLite history for the dev/app database
 *
 * The SQLite baseline is generated by INTROSPECTING a byte-identical copy of
 * the real database, so it describes what the database actually is — not what
 * it should become. Nothing is marked applied here.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const SRC_DB = path.join(ROOT, "prisma", "dev.db");
const MIGRATIONS = path.join(ROOT, "prisma", "migrations");
const PG_ARCHIVE = path.join(ROOT, "prisma", "migrations.postgresql");
const WORK = path.join(ROOT, "e2e", "mig33");
const BASELINE_NAME = "20261001000000_sqlite_baseline";
const PORTABLE = ["20261010000000_phase30_storage_metadata", "20261010000001_phase32_tenant_isolation"];

const sha = (file) => createHash("sha256").update(readFileSync(file)).digest("hex");
const log = (m) => console.log(`[33b] ${m}`);

function tree(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...tree(full));
    else out.push(path.relative(dir, full));
  }
  return out.sort();
}

// ---------------------------------------------------------------- 0. verify
if (!existsSync(SRC_DB)) throw new Error("prisma/dev.db missing — refusing to continue");
const srcHash = sha(SRC_DB);
log(`source hash ${srcHash} (${statSync(SRC_DB).size} bytes) — this script never writes to it`);

// ------------------------------------------------- 1. archive PG migrations
if (!existsSync(PG_ARCHIVE)) {
  const entries = readdirSync(MIGRATIONS, { withFileTypes: true }).filter((e) => e.isDirectory() || e.name === "migration_lock.toml");
  const before = {};
  for (const e of entries) {
    if (e.isDirectory()) for (const f of tree(path.join(MIGRATIONS, e.name))) before[`${e.name}/${f}`] = sha(path.join(MIGRATIONS, e.name, f));
    else before[e.name] = sha(path.join(MIGRATIONS, e.name));
  }
  mkdirSync(PG_ARCHIVE, { recursive: true });
  for (const e of entries) {
    const src = path.join(MIGRATIONS, e.name);
    const dst = path.join(PG_ARCHIVE, e.name);
    if (e.isDirectory()) {
      mkdirSync(dst, { recursive: true });
      for (const f of tree(src)) {
        mkdirSync(path.dirname(path.join(dst, f)), { recursive: true });
        copyFileSync(path.join(src, f), path.join(dst, f));
      }
    } else {
      copyFileSync(src, dst);
    }
  }
  const manifest = Object.entries(before).map(([f, h]) => `${h}  ${f}`).join("\n") + "\n";
  writeFileSync(path.join(PG_ARCHIVE, "MANIFEST.sha256"), manifest);
  writeFileSync(
    path.join(PG_ARCHIVE, "README.md"),
    [
      "# PostgreSQL migration history (preserved, not applied)",
      "",
      "These migrations were authored for a PostgreSQL deployment in Phase 28/30/32.",
      "They are **NOT** applied to the SQLite development database and Prisma never reads this directory.",
      "",
      "Why moved: Prisma supports one migrations directory per schema; the live",
      "`prisma/migrations` directory must serve the SQLite provider used by the app.",
      "Nothing was edited — `MANIFEST.sha256` records each file hash. Verify with:",
      "",
      "    cd prisma/migrations.postgresql && sha256sum -c MANIFEST.sha256",
      "",
      "Restore for a PostgreSQL run with `node scripts/db/restore-postgresql-migrations.mjs`.",
      "",
      "Contents:",
      ...Object.keys(before).map((f) => `- ${f}`),
      "",
    ].join("\n")
  );
  log(`archived ${Object.keys(before).length} PostgreSQL migration files -> prisma/migrations.postgresql/`);
} else {
  log("prisma/migrations.postgresql already exists — leaving it untouched");
}

// --------------------------------------- 2. clear the sqlite history dir only
// PostgreSQL directories are removed from prisma/migrations ONLY after their
// archived copies are proven byte-identical (nothing is lost).
if (existsSync(MIGRATIONS)) {
  const names = readdirSync(MIGRATIONS);
  for (const name of names) {
    const live = path.join(MIGRATIONS, name);
    const archived = path.join(PG_ARCHIVE, name);
    if (existsSync(archived) && statSync(live).isDirectory()) {
      for (const f of tree(live)) {
        if (sha(path.join(live, f)) !== sha(path.join(archived, f))) {
          throw new Error(`refusing to remove ${name}: archived copy of ${f} differs`);
        }
      }
      rmSync(live, { recursive: true, force: true });
      log(`removed ${name} from prisma/migrations (identical copy verified in PostgreSQL archive)`);
    } else if (name !== "migration_lock.toml" && !PORTABLE.includes(name)) {
      throw new Error(`refusing: unexpected entry in prisma/migrations: ${name}`);
    }
  }
  rmSync(path.join(MIGRATIONS, "migration_lock.toml"), { force: true });
}
mkdirSync(MIGRATIONS, { recursive: true });

// ------------------------------- 3. baseline generated from a verified copy
mkdirSync(WORK, { recursive: true });
const baselineCopy = path.join(WORK, "baseline-source.db");
rmSync(baselineCopy, { force: true });
copyFileSync(SRC_DB, baselineCopy);
if (sha(baselineCopy) !== srcHash) throw new Error("copy hash mismatch — aborting");

const ddl = execFileSync(
  process.platform === "win32" ? "npx.cmd" : "npx",
  ["prisma", "migrate", "diff", "--from-empty", "--to-url", `file:${baselineCopy}`, "--script"],
  { cwd: ROOT, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }
);
if (!ddl.includes('CREATE TABLE "users"') || ddl.length < 100000) throw new Error("baseline DDL looks wrong — aborting");

const baselineDir = path.join(MIGRATIONS, BASELINE_NAME);
mkdirSync(baselineDir, { recursive: true });
writeFileSync(
  path.join(baselineDir, "migration.sql"),
  `-- Phase 33 SQLite baseline.\n-- Generated by introspecting a byte-identical copy of prisma/dev.db\n-- (sha256 ${srcHash}). It describes the database AS IT IS, including the\n-- 18 file-metadata columns that the following migrations add.\n-- It is marked applied with \`prisma migrate resolve --applied\`, never executed\n-- against an existing database.\n\n${ddl}`
);
log(`baseline written: ${BASELINE_NAME}/migration.sql (${ddl.split("\n").length} lines)`);

// ------------------------------------- 4. copy portable migrations verbatim
for (const name of PORTABLE) {
  const from = path.join(PG_ARCHIVE, name, "migration.sql");
  if (!existsSync(from)) throw new Error(`missing archived migration ${name}`);
  const to = path.join(MIGRATIONS, name);
  mkdirSync(to, { recursive: true });
  copyFileSync(from, path.join(to, "migration.sql"));
  if (sha(path.join(to, "migration.sql")) !== sha(from)) throw new Error(`${name} copy mismatch`);
  log(`copied ${name} verbatim (identical hash)`);
}

// --------------------------------------------------------- 5. sqlite lock
writeFileSync(path.join(MIGRATIONS, "migration_lock.toml"), 'provider = "sqlite"\n');
log('migration_lock.toml -> provider = "sqlite"');

log(`source hash unchanged: ${sha(SRC_DB) === srcHash}`);
